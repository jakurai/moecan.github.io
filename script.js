// 性格項目
const personality = [
    "yasashisa",
    "itazura",
    "shutoyaka",
    "hade",
    "tsuyoki",
    "uchiki",
    "genki",
    "shy",
    "koukishin",
    "sunao",
    "zen",
    "aku"
];


// 計算
function calculate() {

    const total = {};

    // 最初は全部0
    personality.forEach(key => {
        total[key] = 0;
    });


    // 選択されたタイプ
    const checked =
        document.querySelectorAll(".type-checkbox:checked");


    // 各性格について「一番大きい値」を採用
    checked.forEach(checkbox => {

        const data = typeData[checkbox.value];

        if (!data) return;

        personality.forEach(key => {

            const value = data[key] || 0;

            if (value > total[key]) {
                total[key] = value;
            }

        });

    });


    // 性格値を表示
    personality.forEach(key => {

        const element =
            document.getElementById(key);

        if (element) {
            element.textContent = total[key];
        }

    });


    // 善・悪を除いた合計
    const grandTotal =
        personality
            .filter(key => key !== "zen" && key !== "aku")
            .reduce((sum, key) => {
                return sum + total[key];
            }, 0);


    // 合計表示
    const totalElement =
        document.getElementById("totalValue");

    if (totalElement) {
        totalElement.textContent =
            "合計：" + grandTotal;
    }


    // 課金・善悪判定
    const warning =
        document.getElementById("paymentWarning");

    if (warning) {

        const hasZen = total["zen"] > 0;
        const hasAku = total["aku"] > 0;


        // 善と悪が両方ある
        if (hasZen && hasAku) {

            warning.textContent = "善悪共存は不可";


        // 7500を超える
        } else if (grandTotal > 7500) {

            warning.textContent = "7500超　不可";


        // 5001～7500
        } else if (grandTotal >= 5001) {

            warning.textContent = "要課金";


        // 5000以下
        } else {

            warning.textContent = "5000以下　無課金OK";

        }

    }

} // ← ここが重要


// チェックボックス変更時
document.querySelectorAll(".type-checkbox").forEach(checkbox => {

    checkbox.addEventListener("change", calculate);

});


// リセットボタン
const resetButton =
    document.getElementById("resetButton");

if (resetButton) {

    resetButton.addEventListener("click", () => {

        document.querySelectorAll(".type-checkbox")
            .forEach(checkbox => {
                checkbox.checked = false;
            });

        calculate();

    });

}


// ページを開いたとき
calculate();
